/* 上下文组装：段 N 输入 = 用户需求 + 前序全部产物 + 本段补充 */
function flowBuildUserMessage(idx, state) {
  var st = FLOW_STAGES[idx];
  var parts = [];
  if (idx === 0) {
    parts.push('【需求描述】\n' + (state.req || '').trim());
  } else {
    parts.push('【需求描述】\n' + (state.req || '').trim());
    for (var i = 0; i < idx; i++) {
      var prev = (state.outputs[FLOW_STAGES[i].key] || '').trim();
      if (prev) parts.push('【' + FLOW_STAGES[i].name + '产物】\n' + prev);
    }
    var extra = (state.inputs[st.key] || '').trim();
    if (extra) parts.push('【本段补充约束】\n' + extra);
  }
  return parts.join('\n\n');
}
